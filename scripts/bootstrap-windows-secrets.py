def resolve_github_app_slug(cli_slug: str | None) -> str:
    slug = (
        cli_slug or os.environ.get("PLX_GITHUB_APP_SLUG") or DEFAULT_GITHUB_APP_SLUG
    ).strip()
    github_app_secret_ids(slug)
    return slug


def github_app_secret_ids(slug: str) -> tuple[str, str]:
    if not GITHUB_APP_SLUG_RE.fullmatch(slug):
        raise SystemExit(f"invalid github app slug: {slug}")
    prefix = f"plx/github/apps/{slug}"
    return f"{prefix}/config", f"{prefix}/private-key"


def personal_pat_from_secret(sec: dict) -> str:
    """Legacy-mode precedence. App mode must not call this."""
    for key in PERSONAL_PAT_SECRET_KEYS:
        value = sec.get(key) or ""
        if isinstance(value, str) and value.strip():
            return value.strip()
    return ""


def parse_github_app_config(
    slug: str, config: dict, private_key_pem: str
) -> dict[str, str]:
    config_id, key_id = github_app_secret_ids(slug)
    app_id = str(config.get("appId") or config.get("app_id") or "").strip()
    installation_id = str(
        config.get("installationId") or config.get("installation_id") or ""
    ).strip()
    if not app_id.isdigit() or not installation_id.isdigit():
        raise SystemExit(f"{config_id}: appId and installationId must be numeric")
    pem = private_key_pem.replace("\\n", "\n")
    if "BEGIN" not in pem or "PRIVATE KEY" not in pem:
        raise SystemExit(f"{key_id}: expected a PEM private key")
    return {
        "PLX_GITHUB_APP_SLUG": slug,
        "PLX_GITHUB_APP_ID": app_id,
        "PLX_GITHUB_APP_INSTALLATION_ID": installation_id,
        "PLX_GITHUB_APP_PRIVATE_KEY_SECRET_ID": key_id,
    }


def read_secret_string(client, secret_id: str) -> str:
    try:
        raw = client.get_secret_value(SecretId=secret_id)["SecretString"]
    except ClientError as err:
        code = err.response.get("Error", {}).get("Code", "ClientError")
        raise SystemExit(
            f"{secret_id}: {code}. Refusing to copy personal PATs from {EC2_SECRETS_ID}. "
            "During rollout, re-run with --legacy-personal-pat "
            "(or PLX_BOOTSTRAP_LEGACY_GITHUB_PAT=1)."
        ) from None
    if not isinstance(raw, str) or not raw.strip():
        raise SystemExit(f"{secret_id}: empty secret")
    return raw


def read_json_secret(client, secret_id: str) -> dict:
    raw = read_secret_string(client, secret_id)
    try:
        data = json.loads(raw)
    except json.JSONDecodeError:
        raise SystemExit(f"{secret_id}: expected a JSON object") from None
    if not isinstance(data, dict):
        raise SystemExit(f"{secret_id}: expected a JSON object")
    return data


def load_github_app_binding(client, slug: str) -> dict[str, str]:
    config_id, key_id = github_app_secret_ids(slug)
    config = read_json_secret(client, config_id)
    pem = read_secret_string(client, key_id)
    try:
        return parse_github_app_config(slug, config, pem)
    finally:
        del pem


def github_auth_values(
    sec: dict, *, mode: str, binding: dict[str, str] | None
) -> dict[str, str]:
    """Values this bootstrap may put in a loader. App mode drops every personal PAT."""
    if mode == GITHUB_AUTH_MODE_LEGACY:
        return {"PETRALABX_GITHUB_TOKEN": personal_pat_from_secret(sec)}
    if mode != GITHUB_AUTH_MODE_APP:
        raise SystemExit(f"unknown github auth mode: {mode}")
    if binding is None:
        raise SystemExit("github app binding required")
    for name in PERSONAL_PAT_ENV_NAMES:
        if name in binding:
            raise SystemExit(f"github app binding must not carry {name}")
    return dict(binding)


def git_credential_helper_value() -> str:
    return '!"$HOME/.local/bin/plx-github-app-auth" git-credential'


def app_auth_launcher_sh(python_exe: str, auth_script: str) -> str:
    return "\n".join(
        [
            "#!/bin/sh",
            f"# {GENERATED_MARKER} — do not commit",
            f'exec {sh_quote(python_exe)} {sh_quote(auth_script)} "$@"',
            "",
        ]
    )


def gh_wrapper_sh() -> str:
    return "\n".join(
        [
            "#!/bin/sh",
            f"# {GENERATED_MARKER} — do not commit",
            'exec "$HOME/.local/bin/plx-github-app-auth" gh "$@"',
            "",
        ]
    )


def gh_wrapper_cmd(python_exe: str, auth_script: str) -> str:
    return "\r\n".join(
        [
            "@echo off",
            f"rem {GENERATED_MARKER} — do not commit",
            f'"{python_exe}" "{auth_script}" gh %*',
            "",
        ]
    )


def write_shell_text(path: Path, text: str) -> None:
    """Write a shell script with LF endings.

    Native Windows Python translates newline=None to CRLF, which makes Git
    Bash see `get\\r` from a credential helper and can break the shebang.
    """
    path.write_text(text, encoding="utf-8", newline="\n")


def write_github_app_commands(home: Path, python_exe: str, auth_script: str) -> None:
    bin_dir = home / ".local" / "bin"
    bin_dir.mkdir(parents=True, exist_ok=True)
    launcher = bin_dir / "plx-github-app-auth"
    write_shell_text(launcher, app_auth_launcher_sh(python_exe, auth_script))
    gh = bin_dir / "gh"
    write_shell_text(gh, gh_wrapper_sh())
    (bin_dir / "gh.cmd").write_text(
        gh_wrapper_cmd(python_exe, auth_script), encoding="utf-8", newline=""
    )
    for path in (launcher, gh):
        try:
            path.chmod(0o755)
        except OSError:
            pass


def remove_generated_gh_wrapper(home: Path) -> None:
    bin_dir = home / ".local" / "bin"
    for name in ("plx-github-app-auth", "gh", "gh.cmd"):
        path = bin_dir / name
        try:
            text = path.read_text(encoding="utf-8")
        except OSError:
            continue
        if GENERATED_MARKER in text:
            path.unlink()


