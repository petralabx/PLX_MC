def staging_loader_lines(
    values: dict[str, str], principal_id: str, mode: str = GITHUB_AUTH_MODE_APP
) -> list[str]:
    """PowerShell loader that hydrates atomically and fails closed.

    Everything is fetched into a staging hashtable, every required name is
    validated, and only then is $env:* assigned in one block. On any failure
    nothing is assigned, $global:PlxSecretsLoaderStatus stays 'failed', and the
    loader throws naming the missing variables (never values).
    """
    del principal_id  # retained so callers keep the existing signature
    required_names, optional_names = loader_contract(mode)
    allowed = required_names + optional_names
    for name in values:
        if name not in allowed:
            raise SystemExit(f"loader value {name} is not declared required/optional")
    required = ", ".join(ps_quote(n) for n in required_names)
    optional = ", ".join(ps_quote(n) for n in optional_names)
    lines = [
        "# Machine-local secrets loader for PLX agent workstations",
        "# Generated by scripts/bootstrap-windows-secrets.py — do not commit",
        "#",
        "# Precedence: AWS Secrets Manager only. This file must NEVER fall back",
        "# to credential text files under ~/.aws (TASK-756 / 2026-07-26 outage).",
        "#",
        "# MICROSOFT_GRAPH_TENANT_ID / _CLIENT_ID / _CLIENT_SECRET:",
        f"#   matched set from {CURSOR_GRAPH_SECRET_ID} (PLX_Cursor_Graph).",
        "#   Do not substitute prod/ec2-secrets Graph keys (different app).",
        "#",
        "# Atomic hydrate (TASK-614): stage -> validate -> assign once. On failure no",
        "# $env:* is set, $global:PlxSecretsLoaderStatus stays 'failed', and this file",
        "# throws naming the missing variables. Values are never printed.",
        "#",
        "# GitHub (app mode): PLX_GITHUB_APP_* is an app id plus a private-key",
        "# reference. Personal PATs are not loaded. CIP owns merges.",
        "# GitHub (legacy mode): PETRALABX_GITHUB_TOKEN only, behind",
        "# --legacy-personal-pat.",
        "",
        "$global:PlxSecretsLoaderStatus = 'failed'",
        "$global:PlxSecretsLoaderMissing = ''",
        f"$__plxRequired = @({required})",
        f"$__plxOptional = @({optional})",
        "$__plxStage = @{}",
        "",
    ]
    for key, val in values.items():
        if val:
            lines.append(f"$__plxStage[{ps_quote(key)}] = {ps_quote(val)}")
    lines.extend(
        [
            "",
            "# Microsoft Graph app-only — PLX_Cursor_Graph (matched set)",
            f"# Source of truth: AWS Secrets Manager {CURSOR_GRAPH_SECRET_ID}",
            "# Mail.Send is restricted to cos@petrasoap.com by Exchange RestrictAccess.",
            "$__awsCli = if (Test-Path 'C:\\Program Files\\Amazon\\AWSCLIV2\\aws.exe') {",
            "  'C:\\Program Files\\Amazon\\AWSCLIV2\\aws.exe'",
            "} else { 'aws' }",
            "try {",
            f"  $__graph = & $__awsCli secretsmanager get-secret-value --region us-east-1 --secret-id {CURSOR_GRAPH_SECRET_ID} --query SecretString --output text 2>$null | ConvertFrom-Json",
            "  if ($LASTEXITCODE -ne 0) { throw 'aws cli exited non-zero' }",
            "  $__plxStage['MICROSOFT_GRAPH_TENANT_ID']     = [string]$__graph.tenantId",
            "  $__plxStage['MICROSOFT_GRAPH_CLIENT_ID']     = [string]$__graph.clientId",
            "  $__plxStage['MICROSOFT_GRAPH_CLIENT_SECRET'] = [string]$__graph.clientSecret",
            "} catch {",
            "  # Do not echo the exception message: it can quote payload text.",
            "  $__plxStage.Remove('MICROSOFT_GRAPH_TENANT_ID')",
            "  $__plxStage.Remove('MICROSOFT_GRAPH_CLIENT_ID')",
            "  $__plxStage.Remove('MICROSOFT_GRAPH_CLIENT_SECRET')",
            "}",
            "$__plxStage['AZURE_TENANT_ID']     = $__plxStage['MICROSOFT_GRAPH_TENANT_ID']",
            "$__plxStage['AZURE_CLIENT_ID']     = $__plxStage['MICROSOFT_GRAPH_CLIENT_ID']",
            "$__plxStage['AZURE_CLIENT_SECRET'] = $__plxStage['MICROSOFT_GRAPH_CLIENT_SECRET']",
            "",
            "$__plxMissing = @($__plxRequired | Where-Object { [string]::IsNullOrWhiteSpace([string]$__plxStage[$_]) })",
            "if ($__plxMissing.Count -gt 0) {",
            "  $global:PlxSecretsLoaderMissing = $__plxMissing -join ','",
            "  $__plxNames = $global:PlxSecretsLoaderMissing",
            "  Remove-Variable __plxRequired, __plxOptional, __plxStage, __plxMissing, __graph, __awsCli -ErrorAction SilentlyContinue",
            f'  throw "PLX secrets loader failed: missing $__plxNames (check AWS credentials: aws sts get-caller-identity; fetch source {CURSOR_GRAPH_SECRET_ID}). No environment variables were set."',
            "}",
            "",
            "# Single assignment block — reached only when every required name is present.",
            "foreach ($__plxName in ($__plxRequired + $__plxOptional)) {",
            "  $__plxValue = [string]$__plxStage[$__plxName]",
            "  if (-not [string]::IsNullOrWhiteSpace($__plxValue)) {",
            '    Set-Item -Path "Env:$__plxName" -Value $__plxValue',
            "  }",
            "}",
        ]
    )
    if mode == GITHUB_AUTH_MODE_APP:
        lines.extend(["", *personal_pat_powershell_clear_lines()])
    elif values.get("PETRALABX_GITHUB_TOKEN"):
        lines.extend(["", *github_powershell_reset_lines()])
    lines.extend(
        [
            "$global:PlxSecretsLoaderStatus = 'ok'",
            "Remove-Variable __plxRequired, __plxOptional, __plxStage, __plxMissing, __plxName, __plxValue, __graph, __awsCli -ErrorAction SilentlyContinue",
            "",
            "# Also keep a GitHub-only fragment for profile auto-source:",
            "#   . $HOME\\.secrets-env.github.ps1",
            "",
        ]
    )
    return lines


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--mcp-principal-id",
        default=os.environ.get("MC_MCP_PRINCIPAL_ID", MCP_CURSOR_PRINCIPAL_ID),
        choices=sorted(MCP_PRINCIPAL_IDS),
    )
    parser.add_argument(
        "--legacy-personal-pat",
        action="store_true",
        help="Export PETRALABX_GITHUB_TOKEN from prod/ec2-secrets. Rollout only.",
    )
    parser.add_argument(
        "--github-app-slug",
        default=None,
        help="App under plx/github/apps/<slug> (default plx-agents-writer or PLX_GITHUB_APP_SLUG).",
    )
    return parser.parse_args()


def main() -> None:
    args = parse_args()
    output_staging = staging_output_path(args.mcp_principal_id)
    client = boto3.client("secretsmanager", region_name="us-east-1")
    sec = get_secret_dict(client, EC2_SECRETS_ID)
    registry = (
        {}
        if args.mcp_principal_id == MCP_CURSOR_PRINCIPAL_ID
        else get_secret_dict(client, MCP_AGENT_KEYS_SECRET_ID)
    )
    mcp_key = select_mcp_key(args.mcp_principal_id, sec, registry)
    # Validate cursor-graph exists and has the three keys as a set (fail closed
    # at bootstrap time rather than writing a half-wired loader).
    graph = get_secret_dict(client, CURSOR_GRAPH_SECRET_ID)
    for key in ("tenantId", "clientId", "clientSecret"):
        if not graph.get(key):
            raise SystemExit(
                f"{CURSOR_GRAPH_SECRET_ID}: missing {key} — refusing to write "
                "MICROSOFT_GRAPH_* from any other source"
            )

    # Secrets Manager only — no ~/.aws text-file fallbacks.
    mode = (
        GITHUB_AUTH_MODE_LEGACY
        if args.legacy_personal_pat or legacy_personal_pat_from_env()
        else GITHUB_AUTH_MODE_APP
    )
    binding = None
    if mode == GITHUB_AUTH_MODE_APP:
        slug = resolve_github_app_slug(args.github_app_slug)
        binding = load_github_app_binding(client, slug)
    elif mode == GITHUB_AUTH_MODE_LEGACY:
        print(
            "warning: legacy personal PAT mode is temporary. "
            "Re-run without --legacy-personal-pat after the GitHub App secret exists.",
            file=sys.stderr,
        )

    values = {
        # MICROSOFT_GRAPH_* intentionally omitted here: emitted as a runtime
        # fetch of CURSOR_GRAPH_SECRET_ID so tenant/client/secret stay matched.
        "MC_MCP_API_KEY": mcp_key,
        "MC_MCP_PRINCIPAL_ID": args.mcp_principal_id,
        "MC_OPERATOR_EMAIL": "cos@petrasoap.com",
        "PLX_MC_MCP_ENABLED": "1",
        "SWARM_API_KEY": sec.get("SWARM_API_KEY", ""),
    }
    values.update(github_auth_values(sec, mode=mode, binding=binding))

    lines = staging_loader_lines(values, args.mcp_principal_id, mode)

    output_staging.write_text("\n".join(lines), encoding="utf-8")

    wrote_github = False
    if mode == GITHUB_AUTH_MODE_LEGACY:
        remove_generated_gh_wrapper(HOME)
        gh_token = values.get("PETRALABX_GITHUB_TOKEN") or ""
        if gh_token:
            OUTPUT_GITHUB_PS1.write_text(
                "\n".join(github_powershell_loader_lines(gh_token)),
                encoding="utf-8",
            )
            OUTPUT_GITHUB_SH.write_text(
                "\n".join(github_shell_loader_lines(gh_token)),
                encoding="utf-8",
            )
            try:
                OUTPUT_GITHUB_SH.chmod(0o600)
            except OSError:
                pass
            wrote_github = True
    else:
        if binding is None:
            raise SystemExit("github app binding required")
        write_github_app_commands(HOME, sys.executable, str(AUTH_SCRIPT))
        OUTPUT_GITHUB_PS1.write_text(
            "\n".join(
                github_app_powershell_loader_lines(
                    binding, sys.executable, str(AUTH_SCRIPT)
                )
            ),
            encoding="utf-8",
        )
        OUTPUT_GITHUB_SH.write_text(
            "\n".join(github_app_shell_loader_lines(binding)),
            encoding="utf-8",
        )
        try:
            OUTPUT_GITHUB_SH.chmod(0o600)
            OUTPUT_GITHUB_PS1.chmod(0o600)
        except OSError:
            pass
        wrote_github = True

    print(f"wrote {output_staging}")
    if wrote_github:
        print(f"wrote {OUTPUT_GITHUB_PS1}")
        print(f"wrote {OUTPUT_GITHUB_SH}")
    print("keys loaded:", ", ".join(k for k, v in values.items() if v))
    print(f"graph source: {CURSOR_GRAPH_SECRET_ID} (runtime matched set)")
    print(f"mcp principal: {args.mcp_principal_id}")
    print(f"github auth mode: {mode}")
    if mode == GITHUB_AUTH_MODE_APP and binding is not None:
        print(
            f"github app: {binding['PLX_GITHUB_APP_SLUG']} "
            "(PR-write-only; CIP owns merges)"
        )
        print(
            f"private key reference: {binding['PLX_GITHUB_APP_PRIVATE_KEY_SECRET_ID']}"
        )
    print(
        "tip: source ~/.secrets-env.github (Unix) or "
        "`. $HOME\\.secrets-env.github.ps1` (Windows), then `gh auth status` "
        "must show the GitHub App — see "
        "docs/runbooks/petralabx-github-token-workstation.md"
    )


if __name__ == "__main__":
    main()
