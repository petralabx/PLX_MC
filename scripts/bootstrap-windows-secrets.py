def loader_contract(mode: str) -> tuple[tuple[str, ...], tuple[str, ...]]:
    if mode == GITHUB_AUTH_MODE_APP:
        return LOADER_REQUIRED_ENV + LOADER_GITHUB_APP_ENV, LOADER_OPTIONAL_ENV
    if mode == GITHUB_AUTH_MODE_LEGACY:
        return LOADER_REQUIRED_ENV, LOADER_OPTIONAL_ENV + LOADER_LEGACY_PAT_ENV
    raise SystemExit(f"unknown github auth mode: {mode}")


