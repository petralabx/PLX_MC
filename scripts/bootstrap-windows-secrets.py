#!/usr/bin/env python3
"""Write workstation secret env files from AWS Secrets Manager only.

Precedence (authoritative — do not reverse):
  1. AWS Secrets Manager is the only credential source this script reads.
  2. Never read credential values from files under ~/.aws (that preference
     caused the 2026-07-26 Graph 401 outage / TASK-742 / TASK-756).
  3. MICROSOFT_GRAPH_TENANT_ID / _CLIENT_ID / _CLIENT_SECRET and the matching
     AZURE_TENANT_ID / AZURE_CLIENT_ID / AZURE_CLIENT_SECRET are always a
     matched set from one secret: plx/prod/m365/cursor-graph/v1
     (PLX_Cursor_Graph). PowerShell and Unix loaders fetch that secret at
     source-time so the three values cannot be paired across apps. A missing
     or partial secret exits non-zero and names the missing variables.
  4. The shared Cursor MCP key (sp_mcp_cursor) comes from prod/ec2-secrets,
     or from --compat-secret-id / PLX_BOOTSTRAP_COMPAT_SECRET_ID. In GitHub
     App mode any other principal does not read that secret. Dedicated agent
     keys come from one secret per principal:
     plx/prod/mc/lane-<suffix>-key/v1 (sp_mcp_<suffix>, underscores become
     hyphens). Override with --mcp-key-secret-id. App mode never reads
     plx/prod/mc/mcp-agent-keys/v1 and never falls back to the shared key.
     The loader fetches that lane secret when the file is sourced. A value
     that must be written is stored in a mode 0600 file.

Outputs (never commit; secret-bearing files are mode 0600):
  ~/.secrets-env.staging.ps1   — full PLX agent workstation hydrate (Windows)
  ~/.secrets-env.staging.<principal>.ps1
                                — isolated non-Cursor MCP principal hydrate
  ~/.secrets-env.staging       — Unix hydrate (Cursor)
  ~/.secrets-env.staging.<principal>
                                — Unix hydrate for a dedicated principal
  ~/.secrets-env.github.ps1    — GitHub App fragment (Windows; safe to profile-source)
  ~/.secrets-env.github        — same for bash/zsh (Linux/macOS/DGX)
  ~/.local/bin/plx-github-app-auth
                                — git credential helper / gh token launcher
  ~/.local/bin/gh              — wrapper that mints a short-lived installation token

GitHub auth (default):
  Coding boxes do not receive personal PATs from prod/ec2-secrets
  (PETRALABX_GITHUB_TOKEN, PETRALABX_GITHUB, PLX_GITHUB_PAT, GITHUB_TOKEN).
  They receive an app id plus a private-key *reference*
  (plx/github/apps/<app>/private-key). Default app: plx-agents-writer.
  Set --github-app-slug or PLX_GITHUB_APP_SLUG for a per-bot app.
  Bot apps are PR-write-only. CIP owns merges.
  scripts/github-app-auth.py mints installation tokens and refreshes them
  60 seconds before expiry.

Personal PAT mode was removed (TASK-4361): --legacy-personal-pat and
  PLX_BOOTSTRAP_LEGACY_GITHUB_PAT=1 now exit with an error. A host denied
  prod/ec2-secrets (coding-1) must pass --compat-secret-id. The command exits with the AWS error code and does
  not print secret text.

Usage:
  python scripts/bootstrap-windows-secrets.py
  python scripts/bootstrap-windows-secrets.py --compat-secret-id <smaller-secret>
  python scripts/bootstrap-windows-secrets.py --mcp-principal-id sp_mcp_claude_code
  . ~/.secrets-env.staging.ps1          # full session (Windows)
  source ~/.secrets-env.staging         # full session (Unix)
  . ~/.secrets-env.github.ps1           # GitHub App fragment (Windows)
  source ~/.secrets-env.github          # GitHub App fragment (Unix)

See docs/runbooks/petralabx-github-token-workstation.md and
docs/FLEET-SECRETS-SOP.md § workstation Graph precedence.
"""

