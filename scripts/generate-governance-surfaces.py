#!/usr/bin/env python3
"""Generate derived governance surfaces from config/governance-contract.yaml.

The contract YAML is the single source of truth. This script renders it into:
  - a governance block between marker comments in each `surfaces.marker_files`
    entry (e.g. AGENTS.md, CLAUDE.md)
  - a full rewrite of `surfaces.rule_file` (.cursor/rules/governance.mdc)
  - the handshake modules both MCP servers send as their instructions
    (`handshake.surfaces.mcp_modules`), filled in from the repo registry
  - with --fleet DIR, the handshake block in each tracked repo checked out
    under DIR (`handshake.surfaces.fleet_files`)

Usage:
    python scripts/generate-governance-surfaces.py          # write surfaces
    python scripts/generate-governance-surfaces.py --check  # drift gate, exit 1 on drift
    python scripts/generate-governance-surfaces.py --fleet ..          # write sibling repos' blocks
    python scripts/generate-governance-surfaces.py --fleet .. --check  # exit 1 on a stale block

Run the write mode after every contract edit. Run --check in pre-commit and CI
so no surface can silently drift from the contract.

Requires: pyyaml
"""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
CONTRACT = ROOT / "config" / "governance-contract.yaml"
REGISTRY = ROOT / "config" / "tracked-repos-registry.json"

HANDSHAKE_START = "<!-- plx-mc:handshake:start -->"
HANDSHAKE_END = "<!-- plx-mc:handshake:end -->"
# A hand-written handshake section that --fleet may replace once, on adoption.
HANDWRITTEN_HANDSHAKE = re.compile(
    r"^(## Mission Control handshake\b[^\n]*\n)(.*?)(?=^## |\Z)", re.M | re.S
)

START_MARKER = "<!-- governance:auto:start -->"
END_MARKER = "<!-- governance:auto:end -->"

RULE_FILE_HEADER = """---
description: Core governance doctrine for all code changes
globs:
alwaysApply: true
---

# Governance Doctrine

These rules apply to every code change in this repository. The canonical
source is `config/governance-contract.yaml`; this file is auto-generated by
`scripts/generate-governance-surfaces.py`. Do not edit directly.
"""


def load_contract() -> dict:
    if not CONTRACT.exists():
        print(f"ERROR: {CONTRACT} not found", file=sys.stderr)
        sys.exit(1)
    return yaml.safe_load(CONTRACT.read_text(encoding="utf-8"))


def _bullets(items: list[str]) -> list[str]:
    return [f"- {item}" for item in items]


def _numbered(items: list[str]) -> list[str]:
    return [f"{i}. {item}" for i, item in enumerate(items, start=1)]


def render_block(c: dict) -> str:
    """Render the full governance markdown block, deterministically."""
    out: list[str] = []

    pillars = c.get("pillars", [])
    if pillars:
        out += ["## Core Doctrine Pillars", ""]
        for p in pillars:
            out += [f"{p['ordinal']}. **{p['title']}** — {p['rule']}", ""]

    behavior = c.get("agent_behavior", {})
    if behavior.get("rules"):
        out += [f"## {behavior.get('title', 'Agent Behavioral Contract')}", ""]
        out += _numbered(behavior["rules"]) + [""]

    workflow = c.get("agent_workflow", {})
    if workflow.get("rules"):
        out += [f"## {workflow.get('title', 'Agent Task & PR Workflow')}", ""]
        out += _bullets(workflow["rules"]) + [""]

    hygiene = c.get("repo_hygiene", {})
    if hygiene:
        out += ["## Repo Hygiene", ""]
        for pat in hygiene.get("forbidden_root_patterns", []):
            out.append(f"- FORBIDDEN at repo root: `{pat}`")
        if hygiene.get("report_location"):
            out.append(f"- Reports location: `{hygiene['report_location']}`")
        if hygiene.get("archive_location"):
            out.append(f"- Archive location: `{hygiene['archive_location']}`")
        out += _bullets(hygiene.get("naming_rules", []))
        out.append("")

    standards = c.get("code_standards", {})
    if standards:
        out += ["## Code Standards", ""]
        for lang, spec in standards.items():
            if not isinstance(spec, dict) or not spec.get("rules"):
                continue
            out += [f"### {lang.title()}", ""]
            out += _bullets(spec["rules"]) + [""]

    simple_sections = [
        ("module_boundaries", "Module Boundaries"),
        ("database", "Database Safety"),
        ("branch_hygiene", "Branch Hygiene"),
        ("testing", "Testing"),
        ("safety", "Safety"),
        ("external_integrations", "External Integrations"),
    ]
    for key, title in simple_sections:
        rules = c.get(key, {}).get("rules", [])
        if rules:
            out += [f"## {title}", ""]
            out += _bullets(rules) + [""]

    return "\n".join(out).rstrip() + "\n"


def spliced(text: str, block: str) -> str:
    """Insert/replace the governance block between markers in a marker file."""
    payload = f"{START_MARKER}\n\n{block}\n{END_MARKER}"
    if START_MARKER in text and END_MARKER in text:
        pre = text.split(START_MARKER)[0]
        post = text.split(END_MARKER, 1)[1]
        return pre + payload + post
    return text.rstrip() + "\n\n" + payload + "\n"


def expected_rule_file(block: str) -> str:
    return RULE_FILE_HEADER + "\n" + block


# ---------------------------------------------------------------------------
# Handshake (TASK-4348): one set of steps for both MCP servers and every repo.
# ---------------------------------------------------------------------------
GENERIC_FILL = {
    "repo": "owner/name of the repo under edit",
    "default_bucket": "the registry default bucket",
    "integration_branch": "the integration branch",
}


def load_registry() -> dict[str, dict]:
    """Active tracked repos by slug: default bucket, integration branch, tier."""
    data = json.loads(REGISTRY.read_text(encoding="utf-8"))
    repos: dict[str, dict] = {}
    for r in data.get("repos", []):
        if r.get("status") != "active":
            continue
        repos[r["repo"]] = {
            "default_bucket": r["default_bucket"],
            "integration_branch": r.get("integration_branch") or "main",
            "tier": r.get("tier", ""),
        }
    return dict(sorted(repos.items()))


def fill(text: str, values: dict[str, str]) -> str:
    for key, value in values.items():
        text = text.replace("{" + key + "}", value)
    return text


def repo_values(slug: str, info: dict) -> dict[str, str]:
    return {
        "repo": slug,
        "default_bucket": info["default_bucket"],
        "integration_branch": info["integration_branch"],
    }


def render_fleet_block(h: dict, slug: str, info: dict) -> str:
    values = repo_values(slug, info)
    # No heading inside the block: each repo keeps its own heading (agentic-swarm's
    # is a numbered AR rule with an Enforcement line), so the block fits any layout.
    out = [
        HANDSHAKE_START,
        f"Generated from PLX_MC [`config/governance-contract.yaml`]({h['full_rules']}) by "
        "`scripts/generate-governance-surfaces.py --fleet`. Do not edit this block: change the "
        "contract and regenerate.",
        "",
        f"Before the first edit or any PR on `{slug}`:",
        "",
    ]
    out += [f"{i}. {fill(step, values)}" for i, step in enumerate(h["steps"], start=1)]
    if h.get("notes"):
        out += [""] + [f"- {fill(note, values)}" for note in h["notes"]]
    out += [HANDSHAKE_END]
    return "\n".join(out)


def _js_string(value: str) -> str:
    return json.dumps(value, ensure_ascii=False)


def render_mcp_module(h: dict, repos: dict[str, dict], typescript: bool) -> str:
    """The module both MCP servers import for their instructions."""
    t = (lambda ts: ts) if typescript else (lambda ts: "")
    repo_lines = [
        f"  {_js_string(slug)}: {{ defaultBucket: {_js_string(info['default_bucket'])}, "
        f"integrationBranch: {_js_string(info['integration_branch'])} }},"
        for slug, info in repos.items()
    ]
    lines = [
        "// GENERATED by scripts/generate-governance-surfaces.py from config/governance-contract.yaml",
        "// (handshake) and config/tracked-repos-registry.json (TASK-4348). Do not edit: change the",
        "// contract or the registry and run the generator. Its --check fails on drift.",
        "",
        f"export const HANDSHAKE_TITLE{t(': string')} = {_js_string(h['title'])};",
        "",
        f"export const HANDSHAKE_STEPS{t(': readonly string[]')} = [",
        *[f"  {_js_string(step)}," for step in h["steps"]],
        "];",
        "",
        f"export const HANDSHAKE_NOTES{t(': readonly string[]')} = [",
        *[f"  {_js_string(note)}," for note in h.get("notes", [])],
        "];",
        "",
        f"export const HANDSHAKE_FULL_RULES{t(': string')} = {_js_string(h['full_rules'])};",
        "",
        f"export const HANDSHAKE_REPOS{t(': Readonly<Record<string, { defaultBucket: string; integrationBranch: string }>>')} = {{",
        *repo_lines,
        "};",
        "",
        f"const GENERIC_FILL{t(': Readonly<Record<string, string>>')} = {{",
        *[f"  {k}: {_js_string(v)}," for k, v in GENERIC_FILL.items()],
        "};",
        "",
        f"function fill(text{t(': string')}, values{t(': Record<string, string>')}){t(': string')} {{",
        "  let out = text;",
        "  for (const key of Object.keys(values)) out = out.split(`{${key}}`).join(values[key]);",
        "  return out;",
        "}",
        "",
        "/** The handshake for one repo, numbered, as both MCP servers send it in their instructions. */",
        f"export function renderHandshake(repo{t(': string')}){t(': string')} {{",
        "  // A client may send the slug in any case; the registry's spelling wins.",
        "  const slug = Object.keys(HANDSHAKE_REPOS).find((k) => k.toLowerCase() === repo.trim().toLowerCase());",
        "  const info = slug ? HANDSHAKE_REPOS[slug] : undefined;",
        f"  const values{t(': Record<string, string>')} = slug && info",
        "    ? { repo: slug, default_bucket: info.defaultBucket, integration_branch: info.integrationBranch }",
        "    : { ...GENERIC_FILL, ...(repo.trim() ? { repo: repo.trim() } : {}) };",
        "  const lines = [`${HANDSHAKE_TITLE} for ${values.repo}, before the first edit or any PR:`];",
        "  HANDSHAKE_STEPS.forEach((step, i) => lines.push(`${i + 1}. ${fill(step, values)}`));",
        "  for (const note of HANDSHAKE_NOTES) lines.push(`Also: ${fill(note, values)}`);",
        "  lines.push(`Full rules: ${HANDSHAKE_FULL_RULES}`);",
        '  return lines.join("\\n");',
        "}",
    ]
    return "\n".join(lines) + "\n"


def splice_handshake(text: str, block: str) -> str | None:
    """Replace the marked block, or adopt a hand-written handshake section. None: neither found."""
    if HANDSHAKE_START in text and HANDSHAKE_END in text:
        pre = text.split(HANDSHAKE_START)[0]
        post = text.split(HANDSHAKE_END, 1)[1]
        return pre + block + post
    match = HANDWRITTEN_HANDSHAKE.search(text)
    if match:
        heading = match.group(1)
        rest = text[match.end() :]
        return (
            text[: match.start()]
            + heading
            + "\n"
            + block
            + ("\n\n" + rest if rest else "\n")
        )
    return None


def fleet(h: dict, repos: dict[str, dict], parent: Path, check_mode: bool) -> int:
    """Write or check the handshake block in each tracked repo checked out under parent."""
    by_name = (
        {p.name.lower(): p for p in parent.iterdir() if p.is_dir()}
        if parent.is_dir()
        else {}
    )
    stale: list[str] = []
    for slug, info in repos.items():
        if info["tier"] == "hub":
            continue  # PLX_MC keeps the contract itself and its generated surfaces.
        root = by_name.get(slug.split("/", 1)[1].lower())
        if root is None:
            continue
        block = render_fleet_block(h, slug, info)
        files = (
            h["surfaces"]
            .get("fleet_overrides", {})
            .get(slug, h["surfaces"]["fleet_files"])
        )
        for rel in files:
            path = root / rel
            if not path.exists():
                continue
            label = f"{slug}:{rel}"
            current = path.read_text(encoding="utf-8")
            expected = splice_handshake(current, block)
            if expected is None:
                print(
                    f"note: {label} has no handshake block or section; add the markers by hand",
                    file=sys.stderr,
                )
                continue
            if expected == current:
                continue
            if check_mode:
                if HANDSHAKE_START in current:
                    stale.append(label)
                else:
                    print(
                        f"note: {label} still has a hand-written handshake; adopt it with --fleet",
                        file=sys.stderr,
                    )
            else:
                path.write_text(expected, encoding="utf-8", newline="\n")
                print(f"updated {label}")
    if check_mode:
        if stale:
            print(
                "HANDSHAKE DRIFT — these blocks do not match the contract:",
                file=sys.stderr,
            )
            for label in stale:
                print(f"  - {label}", file=sys.stderr)
            print(
                "Fix: python scripts/generate-governance-surfaces.py --fleet <dir>",
                file=sys.stderr,
            )
            return 1
        print("fleet handshake blocks aligned with contract")
    return 0


def main() -> int:
    args = sys.argv[1:]
    check_mode = "--check" in args
    contract = load_contract()
    handshake = contract.get("handshake")
    if "--fleet" in args:
        idx = args.index("--fleet")
        if idx + 1 >= len(args) or not handshake:
            print(
                "Usage: --fleet <dir holding the repo checkouts> (needs a handshake section)",
                file=sys.stderr,
            )
            return 1
        return fleet(
            handshake, load_registry(), Path(args[idx + 1]).resolve(), check_mode
        )
    block = render_block(contract)
    surfaces = contract.get("surfaces", {})

    drifted: list[str] = []

    for rel in surfaces.get("marker_files", []):
        path = ROOT / rel
        if not path.exists():
            print(f"WARN: marker file missing, skipping: {rel}", file=sys.stderr)
            continue
        current = path.read_text(encoding="utf-8")
        expected = spliced(current, block)
        if current != expected:
            if check_mode:
                drifted.append(rel)
            else:
                path.write_text(expected, encoding="utf-8", newline="\n")
                print(f"updated {rel}")

    rule_rel = surfaces.get("rule_file")
    if rule_rel:
        path = ROOT / rule_rel
        expected = expected_rule_file(block)
        current = path.read_text(encoding="utf-8") if path.exists() else ""
        if current != expected:
            if check_mode:
                drifted.append(rule_rel)
            else:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(expected, encoding="utf-8", newline="\n")
                print(f"updated {rule_rel}")

    if handshake:
        repos = load_registry()
        for rel in handshake["surfaces"]["mcp_modules"]:
            path = ROOT / rel
            expected = render_mcp_module(
                handshake, repos, typescript=rel.endswith(".ts")
            )
            current = path.read_text(encoding="utf-8") if path.exists() else ""
            if current != expected:
                if check_mode:
                    drifted.append(rel)
                else:
                    path.parent.mkdir(parents=True, exist_ok=True)
                    path.write_text(expected, encoding="utf-8", newline="\n")
                    print(f"updated {rel}")

    if check_mode:
        if drifted:
            print(
                "GOVERNANCE DRIFT — surfaces do not match the contract:",
                file=sys.stderr,
            )
            for rel in drifted:
                print(f"  - {rel}", file=sys.stderr)
            print(
                "Fix: python scripts/generate-governance-surfaces.py", file=sys.stderr
            )
            return 1
        print("governance surfaces aligned with contract")
    return 0


if __name__ == "__main__":
    sys.exit(main())
